#!/usr/bin/env bash
# scripts/acceptance/lib.sh — shared helpers for the VOWP acceptance rig.
#
# Source this file from a bash script:
#
#   . "$(dirname -- "$0")/lib.sh"
#
# It never runs a command on source. Every helper that touches tmux takes a
# private TMUX_TMPDIR and a named private socket; there is no fallback to the
# caller's server or to `tmux -L default`.
#
# The helpers are deliberately usable on Linux and macOS: no GNU-only flags,
# no `realpath -m`, no `sha256sum` requirement (it falls back to `shasum`).

# shellcheck shell=bash

if [ -n "${BASH_SOURCE[0]:-}" ]; then
    ACCEPTANCE_LIB_DIR=$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
else
    ACCEPTANCE_LIB_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
fi
readonly ACCEPTANCE_LIB_DIR

acceptance_say() {
    printf 'acceptance: %s\n' "$*"
}

acceptance_warn() {
    printf 'acceptance: warning: %s\n' "$*" >&2
}

acceptance_die() {
    printf 'acceptance: error: %s\n' "$*" >&2
    exit 1
}

acceptance_require_command() {
    command -v "$1" >/dev/null 2>&1 || acceptance_die "required command not found: $1"
}

# Return 0 when a candidate is an acceptance tmux wrapper rather than the real
# binary. Both the host helper wrapper and the in-image wrapper are refused: a
# wrapper that execs another wrapper can recurse or hide the caller's server.
acceptance_is_tmux_wrapper() {
    local candidate=$1
    case "$candidate" in
        "$ACCEPTANCE_LIB_DIR"/*|*/bin/tmux-wrapper)
            return 0
            ;;
    esac
    if [ -n "${VOWP_ACCEPTANCE_ROOT:-}" ]; then
        case "$candidate" in
            "${VOWP_ACCEPTANCE_ROOT%/}/bin/tmux")
                return 0
                ;;
        esac
    fi
    if [ -f "$candidate" ] && head -n 5 "$candidate" 2>/dev/null \
        | grep -q -e 'Generated by scripts/acceptance/lib.sh' \
            -e 'scripts/acceptance/container/tmux-wrapper.sh'; then
        return 0
    fi
    return 1
}

# Resolve the real tmux once, before any wrapper directory is added to PATH.
# The saved path makes repeated calls idempotent after acceptance_env_init has
# prepended its wrapper directory; without it, PATH is scanned past wrappers.
acceptance_find_real_tmux() {
    local saved candidate dir old_ifs
    saved=${VOWP_ACCEPTANCE_REAL_TMUX:-}
    if [ -n "$saved" ] && [ -x "$saved" ] && ! acceptance_is_tmux_wrapper "$saved"; then
        printf '%s\n' "$saved"
        return 0
    fi
    old_ifs=$IFS
    IFS=:
    for dir in $PATH; do
        [ -n "$dir" ] || dir=.
        candidate=$(CDPATH='' cd -- "$dir" 2>/dev/null && pwd) || continue
        candidate=$candidate/tmux
        if [ -x "$candidate" ] && ! acceptance_is_tmux_wrapper "$candidate"; then
            IFS=$old_ifs
            printf '%s\n' "$candidate"
            return 0
        fi
    done
    IFS=$old_ifs
    acceptance_die "tmux is required but was not found on PATH"
}

# Write a tmux wrapper that pins every call to one private socket.
#
# The wrapper refuses an empty/default socket, a missing or shared TMUX_TMPDIR,
# and an explicit `-L default`. It unsets TMUX/TMUX_PANE so an inherited caller
# session can never be targeted by accident.
acceptance_write_tmux_wrapper() {
    local dir=$1
    local real=$2
    [ -n "$dir" ] || acceptance_die "acceptance_write_tmux_wrapper needs a directory"
    [ -n "$real" ] || acceptance_die "acceptance_write_tmux_wrapper needs a real tmux path"
    mkdir -p "$dir"
    cat >"$dir/tmux" <<EOF
#!/bin/sh
# Generated by scripts/acceptance/lib.sh. Never touches the default server.
set -eu
case "\${VOWP_ACCEPTANCE_TMUX_SOCKET:-}" in
    ""|default)
        printf '%s\n' "acceptance tmux: refusing an empty or default socket" >&2
        exit 1
        ;;
esac
case "\${TMUX_TMPDIR:-}" in
    ""|/tmp|/tmp/|/var/tmp|/var/tmp/|/tmp/tmux-*|/var/tmp/tmux-*)
        printf '%s\n' "acceptance tmux: refusing an unset or shared TMUX_TMPDIR: \${TMUX_TMPDIR:-<unset>}" >&2
        exit 1
        ;;
esac
if [ ! -d "\$TMUX_TMPDIR" ]; then
    # tmux silently falls back to the default server when this directory is
    # missing. Refuse before that can happen.
    printf '%s\n' "acceptance tmux: TMUX_TMPDIR does not exist: \$TMUX_TMPDIR" >&2
    exit 1
fi
previous=""
has_socket=0
for arg in "\$@"; do
    if [ "\$previous" = "-L" ] && [ "\$arg" = "default" ]; then
        printf '%s\n' "acceptance tmux: refusing the default tmux socket" >&2
        exit 1
    fi
    case "\$arg" in
        -Ldefault|-L=default)
            printf '%s\n' "acceptance tmux: refusing the default tmux socket" >&2
            exit 1
            ;;
        -S|-S?*)
            printf '%s\n' "acceptance tmux: refusing an explicit -S socket path" >&2
            exit 1
            ;;
        -L|-L?*) has_socket=1 ;;
    esac
    previous=\$arg
done
unset TMUX TMUX_PANE || true
if [ "\$has_socket" -eq 1 ]; then
    exec "$real" "\$@"
fi
exec "$real" -L "\$VOWP_ACCEPTANCE_TMUX_SOCKET" "\$@"
EOF
    chmod 0755 "$dir/tmux"
}

# Create a private HOME, TMPDIR and tmux server directory and export the
# variables a VOWP process needs. Callers still choose VOWP_HOME (or a project
# HOME) for their own scenario; this function only makes the process hermetic.
#
# Usage: acceptance_env_init <root> <socket-name>
acceptance_env_init() {
    local root=$1
    local socket=$2
    local real

    case "$socket" in
        ""|default) acceptance_die "refusing an empty or default tmux socket name: '$socket'" ;;
    esac
    case "$root" in
        ""|/|/tmp|/var/tmp) acceptance_die "refusing an unsafe acceptance root: '$root'" ;;
    esac

    real=$(acceptance_find_real_tmux)
    mkdir -p "$root/user-home" "$root/tmp" "$root/tmux" "$root/bin"
    chmod 0700 "$root/user-home" "$root/tmp" "$root/tmux"

    export HOME="$root/user-home"
    export TMPDIR="$root/tmp"
    export TMUX_TMPDIR="$root/tmux"
    export VOWP_ACCEPTANCE_ROOT="$root"
    export VOWP_ACCEPTANCE_TMUX_SOCKET="$socket"
    export VOWP_TMUX_SOCKET="$socket"
    export VOWP_ACCEPTANCE_REAL_TMUX="$real"
    unset TMUX TMUX_PANE || true
    acceptance_write_tmux_wrapper "$root/bin" "$real"
    case ":$PATH:" in
        *":$root/bin:"*) ;;
        *) export PATH="$root/bin:$PATH" ;;
    esac
}

# Assert that the current environment is safe for a private tmux call.
acceptance_assert_private_tmux() {
    case "${VOWP_ACCEPTANCE_TMUX_SOCKET:-}" in
        ""|default) acceptance_die "VOWP_ACCEPTANCE_TMUX_SOCKET is unset or default" ;;
    esac
    case "${TMUX_TMPDIR:-}" in
        ""|/tmp|/tmp/|/var/tmp|/var/tmp/|/tmp/tmux-*|/var/tmp/tmux-*)
            acceptance_die "TMUX_TMPDIR is unset or shared: ${TMUX_TMPDIR:-<unset>}"
            ;;
    esac
    [ -d "$TMUX_TMPDIR" ] || acceptance_die "TMUX_TMPDIR does not exist: $TMUX_TMPDIR"
    [ -x "$(command -v tmux)" ] || acceptance_die "tmux is not on PATH"
}

# Best-effort stop of the private server created by acceptance_env_init.
acceptance_kill_private_tmux() {
    [ -n "${VOWP_ACCEPTANCE_TMUX_SOCKET:-}" ] || return 0
    [ -n "${TMUX_TMPDIR:-}" ] || return 0
    [ -d "$TMUX_TMPDIR" ] || return 0
    tmux -L "$VOWP_ACCEPTANCE_TMUX_SOCKET" kill-server >/dev/null 2>&1 || true
}

# A portable SHA-256 for a file.
acceptance_sha256_file() {
    local file=$1
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$file" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$file" | awk '{print $1}'
    else
        acceptance_die "sha256sum or shasum is required"
    fi
}

# Lexically normalise a path (absolute or relative to the current directory)
# without resolving symlinks. `acceptance_validate_dest` also checks the
# physical path, so a symlinked parent cannot escape the allowlist.
acceptance_normalize_path() {
    local path=$1 part out=
    local -a parts=()
    case "$path" in
        /*) ;;
        *) path=$PWD/$path ;;
    esac
    IFS=/ read -r -a parts <<<"$path"
    for part in "${parts[@]}"; do
        case "$part" in
            ''|.) ;;
            *) out=$out/$part ;;
        esac
    done
    printf '%s\n' "${out:-/}"
}

# Resolve the deepest existing directory physically, then append the parts that
# do not exist yet. This is what makes `/tmp/link-to-etc/x` fail: the symlink is
# followed before the allowlist check.
acceptance_physical_path() {
    local probe=$1 tail= parent
    while [ ! -d "$probe" ]; do
        case "$probe" in
            /|.) break ;;
        esac
        tail="/$(basename -- "$probe")$tail"
        parent=$(dirname -- "$probe")
        [ "$parent" = "$probe" ] && break
        probe=$parent
    done
    if [ -d "$probe" ]; then
        probe=$(CDPATH='' cd -P -- "$probe" && pwd)
    fi
    printf '%s%s\n' "${probe%/}" "$tail"
}

acceptance_dest_fail() {
    local status=$1
    shift
    printf 'acceptance: error: %s\n' "$*" >&2
    exit "$status"
}

# Reject destinations that could escape their parent or wipe a system root.
# The optional --force paths in the fixture/generator scripts delete the
# destination, so the allowlist is deliberate: only a strict child of /tmp,
# /var/tmp or $HOME is accepted. That denies /etc, /usr, /bin, /sbin, /boot,
# /dev, /proc, /sys, /var, /opt, /root, /home and / even with --force.
# Pass an exit status as the second argument (default 1).
acceptance_validate_dest() {
    local dest=$1 status=${2:-1}
    local lex phys home home_phys tmp_phys vartmp_phys path root allowed
    case "$dest" in
        ""|.|..|/)
            acceptance_dest_fail "$status" "unsafe destination: '$dest'"
            ;;
    esac
    case "$dest" in
        *"/../"*|../*|*/..|*"/.."|*"/./"*|./*|*"/.")
            acceptance_dest_fail "$status" "destination must not contain '..': '$dest'"
            ;;
    esac
    case "$dest" in
        *[[:cntrl:]]*)
            acceptance_dest_fail "$status" "destination must not contain control characters"
            ;;
    esac
    lex=$(acceptance_normalize_path "$dest")
    phys=$(acceptance_physical_path "$lex")
    home=${HOME:-}
    home_phys=
    if [ -n "$home" ] && [ "$home" != "/" ]; then
        home=$(acceptance_normalize_path "$home")
        home_phys=$(acceptance_physical_path "$home")
    fi
    tmp_phys=$(acceptance_physical_path /tmp)
    vartmp_phys=$(acceptance_physical_path /var/tmp)
    for path in "$lex" "$phys"; do
        allowed=0
        case "$path" in
            /root|/root/*) ;;
            *)
                for root in /tmp /var/tmp "$tmp_phys" "$vartmp_phys" "$home" "$home_phys"; do
                    [ -n "$root" ] || continue
                    case "$path" in
                        "${root%/}"/*) allowed=1; break ;;
                    esac
                done
                ;;
        esac
        if [ "$allowed" -ne 1 ]; then
            acceptance_dest_fail "$status" \
                "unsafe destination: '$dest' (allowed: /tmp/..., /var/tmp/..., \$HOME/...)"
        fi
    done
}

# Validate a project-name slug (the same shape VOWP accepts).
acceptance_slug() {
    printf '%s\n' "$1" \
        | tr '[:upper:]' '[:lower:]' \
        | sed -e 's/[^a-z0-9][^a-z0-9]*/-/g' -e 's/^-//' -e 's/-$//'
}
