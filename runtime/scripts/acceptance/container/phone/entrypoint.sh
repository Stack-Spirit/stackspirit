#!/usr/bin/env bash
# scripts/acceptance/container/phone/entrypoint.sh — prepare the phone client.
#
# The rig mounts one generated private key and an ssh_config at
# /run/vowp-rig/phone/. They are copied into the unprivileged phone user's home
# and then the container idles, waiting for `docker exec ... ssh home ...`.
#
# The phone also gets a private tmux directory and the same socket/socket-guard
# environment as the home image. The image's /usr/local/bin/tmux wrapper refuses
# the default socket and an unset/shared TMUX_TMPDIR, so no test running in this
# container can reach a default server.

set -Eeuo pipefail

: "${VOWP_ACCEPTANCE_TMUX_SOCKET:?VOWP_ACCEPTANCE_TMUX_SOCKET must be set by the rig}"
case "$VOWP_ACCEPTANCE_TMUX_SOCKET" in
    ""|default)
        printf '%s\n' "phone-entrypoint: refusing an empty or default tmux socket" >&2
        exit 1
        ;;
esac

tmux_tmpdir=${TMUX_TMPDIR:-/home/phone/.acceptance/tmux}
case "$tmux_tmpdir" in
    ""|/tmp|/tmp/|/var/tmp|/var/tmp/|/tmp/tmux-*|/var/tmp/tmux-*)
        printf '%s\n' "phone-entrypoint: refusing a shared TMUX_TMPDIR: $tmux_tmpdir" >&2
        exit 1
        ;;
esac
install -d -m 0700 -o phone -g phone "$tmux_tmpdir"

if [ ! -f /run/vowp-rig/phone/id_ed25519 ]; then
    printf '%s\n' "phone-entrypoint: /run/vowp-rig/phone/id_ed25519 is missing" >&2
    exit 1
fi
if [ ! -f /run/vowp-rig/phone/config ]; then
    printf '%s\n' "phone-entrypoint: /run/vowp-rig/phone/config is missing" >&2
    exit 1
fi

install -d -m 0700 -o phone -g phone /home/phone/.ssh
install -m 0600 -o phone -g phone /run/vowp-rig/phone/id_ed25519 /home/phone/.ssh/id_ed25519
install -m 0644 -o phone -g phone /run/vowp-rig/phone/config /home/phone/.ssh/config
install -m 0600 -o phone -g phone /dev/null /home/phone/.ssh/known_hosts

cat >/etc/profile.d/acceptance-tmux.sh <<EOF
# Generated by scripts/acceptance/container/phone/entrypoint.sh.
export TMUX_TMPDIR=$tmux_tmpdir
export VOWP_ACCEPTANCE_TMUX_SOCKET=$VOWP_ACCEPTANCE_TMUX_SOCKET
EOF
chmod 0644 /etc/profile.d/acceptance-tmux.sh

printf '%s\n' "acceptance-phone: ready; try: ssh home 'uname -a'" >&2
exec su -s /bin/bash phone -c 'exec sleep infinity'
