#!/usr/bin/env bash
# scripts/acceptance/container/entrypoint.sh — start sshd in the fresh-VPS image.
#
# The rig mounts the concatenated public keys at /run/vowp-rig/authorized_keys.
# The entrypoint installs them for the unprivileged `vowp` user and starts sshd
# in the foreground. It also pins the acceptance tmux socket in every SSH
# session with sshd's SetEnv, so a command run over SSH can never reach the
# default server (the in-image /usr/local/bin/tmux wrapper refuses it anyway).

set -Eeuo pipefail

: "${VOWP_ACCEPTANCE_TMUX_SOCKET:?VOWP_ACCEPTANCE_TMUX_SOCKET must be set by the rig}"

case "$VOWP_ACCEPTANCE_TMUX_SOCKET" in
    ""|default)
        printf '%s\n' "entrypoint: refusing an empty or default tmux socket" >&2
        exit 1
        ;;
esac

tmux_tmpdir=${TMUX_TMPDIR:-/home/vowp/.acceptance/tmux}
case "$tmux_tmpdir" in
    ""|/tmp|/tmp/|/var/tmp|/var/tmp/)
        printf '%s\n' "entrypoint: refusing a shared TMUX_TMPDIR: $tmux_tmpdir" >&2
        exit 1
        ;;
esac

install -d -m 0700 -o vowp -g vowp "$tmux_tmpdir"
install -d -m 0700 -o vowp -g vowp /home/vowp/.ssh

if [ ! -f /run/vowp-rig/authorized_keys ]; then
    printf '%s\n' "entrypoint: /run/vowp-rig/authorized_keys is missing" >&2
    exit 1
fi
install -m 0600 -o vowp -g vowp /run/vowp-rig/authorized_keys /home/vowp/.ssh/authorized_keys

# Host keys are generated on first start; they are disposable because the
# container is too. This is what a fresh VPS does before its first boot.
ssh-keygen -A >/dev/null

install -d -m 0755 /etc/ssh/sshd_config.d
cat >/etc/ssh/sshd_config.d/10-vowp-acceptance.conf <<EOF
# Generated by scripts/acceptance/container/entrypoint.sh.
Port 22
ListenAddress 0.0.0.0
AddressFamily any
PermitRootLogin no
PasswordAuthentication no
KbdInteractiveAuthentication no
ChallengeResponseAuthentication no
PubkeyAuthentication yes
UsePAM yes
AllowUsers vowp
AuthorizedKeysFile .ssh/authorized_keys
StrictModes no
PrintMotd no
X11Forwarding no
AllowTcpForwarding yes
GatewayPorts no
PermitTunnel no
ClientAliveInterval 30
ClientAliveCountMax 3
SetEnv TMUX_TMPDIR=$tmux_tmpdir VOWP_ACCEPTANCE_TMUX_SOCKET=$VOWP_ACCEPTANCE_TMUX_SOCKET VOWP_TMUX_SOCKET=$VOWP_ACCEPTANCE_TMUX_SOCKET
EOF
chmod 0644 /etc/ssh/sshd_config.d/10-vowp-acceptance.conf

printf '%s\n' "acceptance-vps: sshd on 0.0.0.0:22 (user vowp, tmux socket $VOWP_ACCEPTANCE_TMUX_SOCKET)" >&2
exec /usr/sbin/sshd -D -e
