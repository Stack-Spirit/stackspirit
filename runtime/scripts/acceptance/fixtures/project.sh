#!/usr/bin/env bash
# scripts/acceptance/fixtures/project.sh — create one fixture project.
#
# Usage:
#   project.sh hello      <dest> [--name NAME] [--force]
#   project.sh memory-hog <dest> [--name NAME] [--hog-mb N] [--hog-hold S] [--force]
#
# The result is an ordinary git checkout with:
#   * a real `vowp.toml` that uses a committed fake CLI harness;
#   * a bare local origin next to it (`<dest>-origin.git`), so merges work
#     without the network;
#   * `.acceptance/seed-jobs.sh`, which adds ready-to-run jobs;
#   * for `memory-hog`, a worker that allocates and holds memory before it
#     writes its report.
#
# Nothing is registered with a VOWP home here. v0.2 tests register the checkout
# with `vowp project add` (planned for C2). A v0.1 home needs a separate `vowp init` checkout
# first: v0.1 init refuses while this fixture's `vowp.toml` exists, and --force
# would overwrite the fake-harness config.
#
# The script is safe to run inside the fresh-VPS container (the rig mounts this
# directory read-only at /opt/vowp-acceptance) or on the host. It never reads
# the host's ~/.vowp, never calls tmux, and never touches the network.

set -Eeuo pipefail

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
WORKER_SOURCE="$SCRIPT_DIR/fake-worker.sh"

# The shared validator is authoritative here too, so the fixture and the v0.1
# generator can never drift into different destination rules.
# shellcheck source=../lib.sh
. "$SCRIPT_DIR/../lib.sh"

say() {
    printf 'acceptance fixture: %s\n' "$*"
}

die() {
    printf 'acceptance fixture: error: %s\n' "$*" >&2
    exit 1
}

usage() {
    sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
}

[ "$#" -ge 2 ] || usage
kind=$1
dest=$2
shift 2

name=
force=0
hog_mb=256
hog_hold=20
while [ "$#" -gt 0 ]; do
    case "$1" in
        --name)
            [ "$#" -ge 2 ] || die "--name needs a value"
            name=$2
            shift 2
            ;;
        --hog-mb)
            [ "$#" -ge 2 ] || die "--hog-mb needs a value"
            hog_mb=$2
            shift 2
            ;;
        --hog-hold)
            [ "$#" -ge 2 ] || die "--hog-hold needs a value"
            hog_hold=$2
            shift 2
            ;;
        --force) force=1; shift ;;
        -h|--help) usage ;;
        *) die "unknown option: $1" ;;
    esac
done

case "$kind" in
    hello|memory-hog) ;;
    *) die "kind must be hello or memory-hog" ;;
esac
case "$hog_mb" in
    ''|*[!0-9]*) die "--hog-mb must be a whole number" ;;
esac
case "$hog_hold" in
    ''|*[!0-9]*) die "--hog-hold must be a whole number" ;;
esac

[ -n "$dest" ] || die "destination is required"
acceptance_validate_dest "$dest"

if [ -e "$dest" ] && [ -n "$(ls -A "$dest" 2>/dev/null)" ]; then
    if [ "$force" != "1" ]; then
        die "destination is not empty: $dest (pass --force to replace it)"
    fi
    rm -rf -- "$dest"
fi
mkdir -p "$dest/.acceptance/bin" "$dest/.acceptance/adapters" "$dest/src"
dest=$(CDPATH='' cd -- "$dest" && pwd)
origin="${dest}-origin.git"
if [ -e "$origin" ]; then
    if [ "$force" != "1" ]; then
        die "origin already exists: $origin (pass --force to replace it)"
    fi
    rm -rf -- "$origin"
fi

if [ -z "$name" ]; then
    name=$(basename "$dest")
fi
name=$(printf '%s\n' "$name" \
    | tr '[:upper:]' '[:lower:]' \
    | sed -e 's/[^a-z0-9][^a-z0-9]*/-/g' -e 's/^-//' -e 's/-$//')
[ -n "$name" ] || die "could not derive a valid project name; pass --name"

[ -x "$WORKER_SOURCE" ] || die "fake worker is missing or not executable: $WORKER_SOURCE"

install -m 0755 "$WORKER_SOURCE" "$dest/.acceptance/bin/fake-worker"
harness=acceptance-hello
worker="$dest/.acceptance/bin/fake-worker"
if [ "$kind" = "memory-hog" ]; then
    harness=acceptance-hog
    worker="$dest/.acceptance/bin/hog-worker"
    cat >"$dest/.acceptance/bin/hog-worker" <<EOF
#!/usr/bin/env bash
# Generated by scripts/acceptance/fixtures/project.sh: a memory-hog harness.
set -Eeuo pipefail
exec "\$(CDPATH='' cd -- "\$(dirname -- "\$0")" && pwd)/fake-worker" --hog --mb $hog_mb --hold $hog_hold "\$@"
EOF
    chmod 0755 "$dest/.acceptance/bin/hog-worker"
fi

cat >"$dest/.acceptance/adapters/$harness.toml" <<EOF
# Generated by scripts/acceptance/fixtures/project.sh.
name = "$harness"
provider = "fake"

[command]
argv = ["$worker"]
prompt_via = "stdin"

[output]
format = "text"
text_chunk_lines = 1

[exit]
ok = [0]
EOF

cat >"$dest/vowp.toml" <<EOF
# Generated by scripts/acceptance/fixtures/project.sh. Fake harness only;
# this fixture never starts a real claude/opencode process or a model turn.
[node]
name = "acceptance-local"
max_workers = 4
max_verifiers = 2
tick_secs = 1
tz_offset_minutes = 0

[project]
name = "$name"
remote = "origin"
default_branch = "main"
check_cmds = []
lock_files = ["Cargo.lock"]
always_allowed = ["Cargo.lock"]
push = true

[profiles.planner]
ladder = ["cli:$harness"]
on_quota = "park"

[profiles.keeper]
ladder = ["cli:$harness"]
on_quota = "park"

[profiles.worker]
ladder = ["cli:$harness"]
on_quota = "park"

[profiles.verifier]
ladder = ["cli:$harness"]
on_quota = "park"

[harnesses.$harness]
mapping = ".acceptance/adapters/$harness.toml"
env_pass = ["VOWP_ACCEPTANCE_WORKER_LOG"]
EOF

cat >"$dest/.gitignore" <<'EOF'
.vowp/
target/
EOF

cat >"$dest/README.md" <<EOF
# acceptance fixture: $name

Generated by \`scripts/acceptance/fixtures/project.sh\` for the VOWP acceptance
rig. The worker is a fake harness; it never calls a model or the network.

Kind: \`$kind\`
$(if [ "$kind" = "memory-hog" ]; then printf '%s\n' "Memory: ${hog_mb} MiB for ${hog_hold}s per job."; fi)

Use \`.acceptance/seed-jobs.sh [count]\` to add jobs, then start the supervisor
with the \`vowp\` command under test. The project's \`origin\` is a local bare
repository at \`$origin\`.
EOF

cat >"$dest/.acceptance/seed-jobs.sh" <<'EOF'
#!/usr/bin/env bash
# Add `count` independent fake-harness jobs to this fixture project.
#
# Usage: .acceptance/seed-jobs.sh [count] [prefix]
#        VOWP=/path/to/vowp .acceptance/seed-jobs.sh 4 hog
#
# Run from the project root. Register the project with v0.2 `vowp project add`
# (planned for C2) before starting a supervisor. The fake worker writes
# src/<job>.txt, commits it, and writes the report the `report` gate needs.
set -Eeuo pipefail

count=${1:-1}
prefix=${2:-job}
VOWP=${VOWP:-vowp}
case "$count" in
    ''|*[!0-9]*) printf '%s\n' "seed-jobs: count must be a whole number" >&2; exit 2 ;;
esac
[ "$count" -ge 1 ] || { printf '%s\n' "seed-jobs: count must be at least 1" >&2; exit 2; }

index=1
while [ "$index" -le "$count" ]; do
    id="${prefix}-${index}"
    body=$(cat <<BRIEF
# Goal

Create \`src/${id}.txt\` with exactly one line: \`fake acceptance worker finished ${id}\`.

# Read first

- \`README.md\` in this worktree.

# Deliverables

- \`src/${id}.txt\`.

# Tests required

- The job's report gate must pass.

# Done when

\`src/${id}.txt\` exists and the report has \`status: done\`.
BRIEF
)
    printf '%s\n' "$body" | "$VOWP" job add \
        --id "$id" \
        --title "Acceptance fixture $id" \
        --kind build \
        --owns "src/${id}.txt" \
        --gates "report,owns_respected" \
        --brief - >/dev/null
    printf '%s\n' "seed-jobs: added $id"
    index=$((index + 1))
done
EOF
chmod 0755 "$dest/.acceptance/seed-jobs.sh"

cat >"$dest/.acceptance/project.json" <<EOF
{
  "format": 1,
  "kind": "$kind",
  "name": "$name",
  "path": "$dest",
  "origin": "$origin",
  "harness": "$harness",
  "worker": "$worker",
  "hog_mb": $hog_mb,
  "hog_hold": $hog_hold
}
EOF

git -C "$dest" init -q -b main
git -C "$dest" config user.name "Acceptance Fixture"
git -C "$dest" config user.email "acceptance@example.invalid"
git init -q --bare -b main "$origin"
git -C "$dest" remote add origin "$origin"
git -C "$dest" add -A
git -C "$dest" commit -q -m "$name: acceptance fixture"
git -C "$dest" push -q -u origin main

say "created $kind project $name at $dest"
say "origin: $origin"
say "jobs: cd $dest && .acceptance/seed-jobs.sh 2"
